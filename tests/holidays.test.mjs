const yearOf = (y) => getHolidaysInRange(new Date(y, 0, 1), new Date(y + 1, 0, 1));

for (const [year, expected] of Object.entries(VECTORS)) {
  test(`holidays of ${year} match exactly (date and name)`, () => {
    const y = Number(year);
    assert.deepEqual(yearOf(y), expected.map(([date, name]) => ({ date, name })));
    // Same answer through the string-bound API and per-day lookup.
    assert.deepEqual(getHolidaysInRange(`${y}-01-01`, `${y + 1}-01-01`), yearOf(y));
    for (const [date, name] of expected) assert.equal(getHolidayName(date), name, date);
  });
}

test('date sets match the official 内閣府 CSV for every year 2000–2027', () => {
  for (const [year, mmdd] of Object.entries(OFFICIAL_DATE_SETS)) {
    const expected = mmdd.split(' ').map((s) => `${year}-${s.slice(0, 2)}-${s.slice(2)}`);
    assert.deepEqual(yearOf(Number(year)).map((h) => h.date), expected, `year ${year}`);
  }
});

test('equinox holidays match the NAOJ table 2020–2050', () => {
  for (const [year, [vernal, autumnal]] of Object.entries(NAOJ_EQUINOXES)) {
    assert.equal(getHolidayName(`${year}-03-${vernal}`), '春分の日', `${year} 春分`);
    assert.equal(getHolidayName(`${year}-09-${autumnal}`), '秋分の日', `${year} 秋分`);
  }
});

test('rule changes before 2007 and other edge cases', () => {
  assert.equal(getHolidayName('2006-04-29'), 'みどりの日');
  assert.equal(getHolidayName('2007-04-29'), '昭和の日');
  assert.equal(getHolidayName('2006-05-04'), '国民の休日', 'pre-2007 5/4 sandwich');
  assert.equal(getHolidayName('2003-05-04'), null, 'pre-2007: a Sunday is never a 国民の休日');
  assert.equal(getHolidayName('2003-05-05'), 'こどもの日');
  assert.equal(getHolidayName('2002-07-20'), '海の日');
  assert.equal(getHolidayName('2018-12-23'), '天皇誕生日');
  assert.equal(getHolidayName('2019-12-23'), null, 'no 天皇誕生日 in 2019');
  assert.equal(getHolidayName('2020-10-12'), null, 'no October スポーツの日 in 2020');
  assert.equal(getHolidayName('2021-10-11'), null, 'no October スポーツの日 in 2021');
  assert.equal(getHolidayName('2020-08-11'), null, '山の日 moved in 2020');
  assert.equal(getHolidayName('2032-09-21'), '国民の休日');
  assert.equal(getHolidayName('2092-03-19'), '春分の日', 'the only 3/19 春分の日');
});

test('getHolidayName accepts Dates (local calendar date, any time of day)', () => {
  assert.equal(getHolidayName(new Date(2026, 0, 1)), '元日');
  assert.equal(getHolidayName(new Date(2026, 0, 1, 23, 59, 59)), '元日');
  assert.equal(getHolidayName(new Date(2026, 8, 22, 12)), '国民の休日');
  assert.equal(getHolidayName(new Date(2026, 9, 4)), null);
});

test('getHolidayName rejects bad input and unsupported years', () => {
  for (const bad of [null, undefined, '', 'abc', '2026-1-1', '2026-02-30', 20260101, {}, new Date(NaN)]) {
    assert.equal(getHolidayName(bad), null, String(bad));
  }
  assert.equal(getHolidayName('1999-01-01'), null);
  assert.equal(getHolidayName('2100-01-01'), null);
  assert.equal(getHolidayName('2099-01-01'), '元日');
  assert.equal(getHolidayName('2000-01-01'), '元日');
});

test('getHolidaysInRange: half-open bounds, partial days, year boundaries', () => {
  // The 2026 Silver Week: 9/21 敬老の日, 9/22 国民の休日, 9/23 秋分の日.
  assert.deepEqual(getHolidaysInRange(new Date(2026, 8, 21), new Date(2026, 8, 23)), [
    { date: '2026-09-21', name: '敬老の日' },
    { date: '2026-09-22', name: '国民の休日' },
  ], 'end exclusive');
  assert.deepEqual(getHolidaysInRange(new Date(2026, 8, 21, 12), new Date(2026, 8, 21, 13)),
    [{ date: '2026-09-21', name: '敬老の日' }], 'a range inside a day still overlaps that day');
  assert.deepEqual(getHolidaysInRange(new Date(2026, 8, 22, 23), new Date(2026, 8, 23, 0, 1)), [
    { date: '2026-09-22', name: '国民の休日' },
    { date: '2026-09-23', name: '秋分の日' },
  ]);
  assert.deepEqual(getHolidaysInRange(new Date(2026, 11, 27), new Date(2027, 0, 12)), [
    { date: '2027-01-01', name: '元日' },
    { date: '2027-01-11', name: '成人の日' },
  ], 'across a year boundary, sorted');
  // A 42-day month grid of 2026-05 (Sunday start: 4/26–6/6).
  assert.deepEqual(getHolidaysInRange(new Date(2026, 3, 26), new Date(2026, 5, 7)).map((h) => h.date),
    ['2026-04-29', '2026-05-03', '2026-05-04', '2026-05-05', '2026-05-06']);
  assert.equal(getHolidaysInRange(new Date(1990, 0, 1), new Date(2110, 0, 1)).length,
    Array.from({ length: 100 }, (_, i) => yearOf(2000 + i).length).reduce((a, b) => a + b, 0),
    'out-of-range years are skipped, supported years are complete');
});

test('getHolidaysInRange returns [] for empty, inverted or invalid ranges', () => {
  assert.deepEqual(getHolidaysInRange(new Date(2026, 0, 1), new Date(2026, 0, 1)), []);
  assert.deepEqual(getHolidaysInRange(new Date(2026, 0, 2), new Date(2026, 0, 1)), []);
  assert.deepEqual(getHolidaysInRange(null, new Date(2026, 0, 1)), []);
  assert.deepEqual(getHolidaysInRange(new Date(NaN), new Date(2026, 0, 1)), []);
  assert.deepEqual(getHolidaysInRange('2026-01-01', 'bad'), []);
});

test('results do not depend on the device time zone', () => {
  const url = new URL('../js/util/holidays-jp.js', import.meta.url).href;
  const code = `const M = await import(${JSON.stringify(url)});
    process.stdout.write(JSON.stringify({
      year: M.getHolidaysInRange(new Date(2026, 0, 1), new Date(2027, 0, 1)),
      byDate: M.getHolidayName(new Date(2026, 8, 22, 0, 0)),
      byDateLate: M.getHolidayName(new Date(2026, 8, 22, 23, 59)),
    }));`;
  for (const tz of ['America/Los_Angeles', 'Pacific/Kiritimati', 'UTC']) {
    const out = JSON.parse(execFileSync(process.execPath, ['--input-type=module', '-e', code], {
      env: { ...process.env, TZ: tz }, encoding: 'utf8',
    }));
    assert.deepEqual(out.year, VECTORS[2026].map(([date, name]) => ({ date, name })), tz);
    assert.equal(out.byDate, '国民の休日', tz);
    assert.equal(out.byDateLate, '国民の休日', tz);
  }
});
